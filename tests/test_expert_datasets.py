@pytest.mark.parametrize(("made", "config"), [("oracle_dataset", FLIGHT), ("drift_dataset", TINY)])
def test_dataset_replays_bitwise_from_its_seeds(made, config, request):
    ds, _ = request.getfixturevalue(made)
    for seed, (first, rows) in zip(ds.seeds, episodes(ds), strict=True):
        env = make(SID, **config)
        obs, _ = env.reset(seed=int(str(seed), 16))
        assert np.array_equal(ds.observations[first], obs)
        for k, action in enumerate(ds.actions[rows]):
            obs, reward, terminated, truncated, _ = env.step(action)
            step = rows.start + k
            assert np.array_equal(ds.observations[first + k + 1], obs)
            assert ds.rewards[step] == reward
            assert (ds.terminations[step], ds.truncations[step]) == (terminated, truncated)


