REPO = Path(__file__).resolve().parents[1]


def public_seed_hex(split, index, count):
    """The seed of episode `index` under either name the scenario's seeds may be keyed by."""
    return {f"{SeedSplit(key, split, count).seed(index):032x}" for key in (SID, NAME)}


def hidden_seeds(count):
    """The test split's episode and agent seeds under the hidden key now in the environment."""
    found = set()
    for key in (SID, NAME):
        split = SeedSplit(key, "test", count)
        for k in range(count):
            found |= {split.seed(k), split.agent_seed(k)}
    return found


def front_matter(card):
    lines = card.splitlines()
    assert lines[0] == "---"
    end = lines.index("---", 1)
    return "\n".join(lines[1:end]), "\n".join(lines[end + 1 :])


def card_value(head, key):
    match = re.search(rf"^{key}:[ \t]*(.*)$", head, re.M)
    assert match is not None, f"the card has no {key} field"
    return match.group(1).strip()


def episodes(ds):
    """(first observation row, step slice) of every episode."""
    starts = np.r_[ds.episode_starts, len(ds.actions)]
    return [(starts[i] + i, slice(starts[i], starts[i + 1])) for i in range(len(ds.seeds))]


def oracle_expert_dataset(**config):
    return expert_dataset(
        SID, "validation", [0], agent=OracleAgent(config=FAST), **{**FLIGHT, **config}
    )


class _CountedSolves:
    """The oracle's own `solve`, recording the steps left in each view it was given."""

    def __init__(self, solve):
        self.solve = solve
        self.steps_left = []

    def __call__(self, view, obs):
        self.steps_left.append(view.max_steps)
        return self.solve(view, obs)


