def test_oracle_agent_succeeds_within_its_certified_bracket(oracle_flight):
    ep = oracle_flight
    assert success(ep)
    bounds = bounds_for(ep, oracle=FuelOracle(config=FAST))
    assert math.isfinite(bounds.upper)
    e1b = delta_v_axes(ep)
    assert bounds.lower <= e1b <= bounds.upper * (1 + 1e-6)


def test_oracle_agent_takes_only_what_every_agent_gets():
    assert list(inspect.signature(OracleAgent.reset).parameters)[1:] == ["view", "rng"]
    assert list(inspect.signature(OracleAgent.act).parameters)[1:] == ["obs", "info"]
    assert isinstance(OracleAgent().name, str)


def test_oracle_agent_plans_from_its_first_observation_without_an_environment(first_plan):
    view, plan = first_plan
    agent = OracleAgent(config=FAST)
    agent.reset(view, agent_generator(1))
    # Open loop by default: later observations do not change the plan, so feeding the first one
    # again still flies the next rows.
    flown = [agent.act(OBS.copy(), {"time_s": view.dt * k}) for k in range(3)]
    np.testing.assert_allclose(flown, plan[:3] / view.max_accel, rtol=1e-12, atol=1e-15)


def test_oracle_agent_follows_the_observation_not_the_true_state():
    env = make(SID, max_steps=STEPS)
    view = env.agent_view()
    truth, _ = env.reset(seed=SeedSplit(SID, "train", 1).seed(0))
    shown = truth + np.array([60.0, -40.0, 25.0, 0.0, 0.0, 0.0])
    agent = OracleAgent(config=FAST)
    agent.reset(view, agent_generator(2))
    first = agent.act(shown, INFO)
    plan = FuelOracle(config=FAST).solve(view, shown).plan
    np.testing.assert_allclose(first, plan[0] / view.max_accel, rtol=1e-12, atol=1e-15)
    assert not np.allclose(
        first, FuelOracle(config=FAST).solve(view, truth).plan[0] / view.max_accel
    )


def test_oracle_agent_is_deterministic_whatever_its_random_stream():
    view = make(SID, max_steps=STEPS).agent_view()
    obs = np.array([-380.0, -60.0, 30.0, -0.01, 0.04, 0.0])
    actions = []
    for seed in (3, 4):
        agent = OracleAgent(config=FAST)
        agent.reset(view, agent_generator(seed))
        actions.append(agent.act(obs, INFO))
    assert np.array_equal(actions[0], actions[1])


def test_oracle_agent_answers_in_acceleration_units_in_accel_mode(first_plan):
    view, plan = first_plan
    agent = OracleAgent(config=FAST)
    agent.reset(replace(view, action_mode="accel"), agent_generator(5))
    np.testing.assert_allclose(agent.act(OBS, INFO), plan[0], rtol=1e-12, atol=1e-18)


def test_oracle_agent_answers_in_newtons_at_the_initial_mass_in_thrust_mode(first_plan):
    view, plan = first_plan
    agent = OracleAgent(config=FAST)
    agent.reset(replace(view, action_mode="thrust"), agent_generator(9))
    flown = [agent.act(OBS, INFO) for _ in range(3)]
    np.testing.assert_allclose(flown, plan[:3] * view.mass_kg, rtol=1e-12, atol=1e-15)


def test_thrust_mode_dataset_records_the_mode_and_overshoots_the_plan(oracle_dataset):
    accel, _ = oracle_dataset
    thrust = oracle_expert_dataset(action_mode="thrust")
    view = make(SID, **FLIGHT).agent_view()
    assert thrust.card["scenario_ids"].endswith(":action_mode=thrust:violation_samples=2")
    assert np.array_equal(thrust.observations[0], accel.observations[0])
    # Every command is the same plan row at the initial mass, in newtons.
    np.testing.assert_allclose(
        thrust.actions, accel.actions * view.max_accel * view.mass_kg, rtol=1e-12, atol=1e-12
    )
    # As propellant is spent the same force accelerates less mass, so the flown delta-v exceeds
    # the plan's.
    e1 = [float(ds.card["e1_summary"].split()[1]) for ds in (accel, thrust)]
    assert e1[1] > e1[0]


def test_oracle_agent_raises_when_no_plan_is_verified():
    env = make(SID, **UNREACHABLE)
    obs, _ = env.reset(seed=SeedSplit(SID, "validation", 1).seed(0))
    view = env.agent_view()
    assert FuelOracle(config=FAST).solve(view, obs).plan is None
    agent = OracleAgent(config=FAST)
    agent.reset(view, agent_generator(10))
    with pytest.raises(RuntimeError, match="no plan"):
        agent.act(obs, INFO)


def test_replanning_oracle_solves_every_k_steps_until_its_arrival(replanned_flight):
    _, agent, steps_left = replanned_flight
    solved_at = [FLIGHT["max_steps"] - left for left in steps_left]
    assert len(solved_at) >= 2
    assert solved_at == list(range(0, agent.arrival, REPLAN))


def test_replanning_oracle_succeeds_within_the_open_loop_bracket(replanned_flight):
    ep, _, _ = replanned_flight
    assert success(ep)
    bounds = bounds_for(ep, oracle=FuelOracle(config=FAST))
    e1b = delta_v_axes(ep)
    # The lower bound holds for any successful flight. The upper one is the open-loop plan's
    # cost; with perfect navigation each replan restarts from that plan's own state and finds
    # its remainder again, which the agent does not promise in general.
    assert bounds.lower <= e1b <= bounds.upper * (1 + 1e-6)


