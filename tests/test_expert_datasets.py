def _attack(path, hidden):
    """Every way a holder of the dataset files could find a hidden seed; returns those found."""
    card = path.with_suffix(".md").read_text(encoding="utf-8")
    with np.load(path, allow_pickle=False) as npz:
        arrays = {name: npz[name] for name in npz.files}
    blobs = [card.encode(), path.read_bytes(), *(a.tobytes() for a in arrays.values())]
    stored = [str(s) for name in ("seeds", "agent_seeds") for s in arrays.get(name, ())]
    text = " ".join([card, *stored])
    tokens = set(re.findall(r"[0-9a-fA-F]{16,}|\d{6,}", text))
    found = set()
    for token in tokens:
        # A seed written out in hex or decimal.
        for base in (16, 10):
            try:
                if int(token, base) in hidden:
                    found.add(int(token, base))
            except ValueError:
                pass
        # A token used as the hidden key itself.
        for key in (SID, NAME):
            for k in range(10):
                for stream in ("episode", "agent"):
                    seed = derive_seed("vbar test seeds " + token, key, k, stream)
                    if seed in hidden:
                        found.add(seed)
    for seed in hidden:
        encodings = [
            f"{seed:032x}".encode(),
            f"{seed:032x}".encode("utf-32-le"),
            str(seed).encode(),
            str(seed).encode("utf-32-le"),
            seed.to_bytes(16, "big"),
            seed.to_bytes(16, "little"),
        ]
        if any(e in blob for e in encodings for blob in blobs):
            found.add(seed)
    return found


def test_an_attacker_with_the_first_ten_episodes_recovers_no_hidden_seed(monkeypatch, tmp_path):
    key = secrets.token_hex(32)
    monkeypatch.setenv(HIDDEN_KEY_VARIABLE, key)
    hidden = hidden_seeds(10)
    ds = expert_dataset(SID, "train", range(10), agent=DriftAgent(), **TINY)
    path = tmp_path / "train.npz"
    ds.save(path)
    assert _attack(path, hidden) == set()
    blob = path.read_bytes() + path.with_suffix(".md").read_bytes()
    assert key.encode() not in blob and key.encode("utf-32-le") not in blob
    # No hidden episode was flown: none of their first observations is in the data.
    env = make(SID, max_steps=2)
    for key in (SID, NAME):
        for seed in SeedSplit(key, "test", 10):
            first, _ = env.reset(seed=seed)
            assert not np.any(np.all(ds.observations == first, axis=1))


def test_datasets_are_identical_under_any_hidden_key(monkeypatch, tmp_path):
    # Files that do not change with the hidden key carry no information about it.
    files = []
    for run, key in enumerate((secrets.token_hex(32), secrets.token_hex(32), None)):
        if key is None:
            monkeypatch.delenv(HIDDEN_KEY_VARIABLE, raising=False)
        else:
            monkeypatch.setenv(HIDDEN_KEY_VARIABLE, key)
        path = tmp_path / f"run{run}.npz"
        expert_dataset(SID, "validation", range(4), agent=DriftAgent(), **TINY).save(path)
        files.append(path.read_bytes() + path.with_suffix(".md").read_bytes())
    assert files[0] == files[1] == files[2]


# Written by Python, pytest, linters and environments, not by the script under test.
SKIPPED_DIRS = {".git", ".venv", "venv", "__pycache__", ".hypothesis"}


def _tree(root):
    """Every path under `root` with its size and modification time, cache directories left out."""
    found = {}
    for top, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIPPED_DIRS and not d.endswith("_cache")]
        for name in dirs:
            found[os.path.join(top, name)] = None
        for name in files:
            stat = os.stat(os.path.join(top, name))
            found[os.path.join(top, name)] = (stat.st_size, stat.st_mtime_ns)
    return found


