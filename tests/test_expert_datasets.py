SID = "vbar:approach-rbar:cw:box:dv:v1"
NAME = "approach-rbar"
# 100 steps leave 400 s before the 600 s dwell, enough for the dispersed starts of the first
# validation seeds, and keep one oracle solve near 0.3 s.
STEPS = 100
SHORT = {"max_steps": STEPS, "violation_samples": 2}
# 1020 s, as long as the 100 steps above, in a third of the steps: validation seeds 0 and 1
