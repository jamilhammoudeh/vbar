def _tampered(source, tmp_path, how):
    """A copy of a saved dataset whose NPZ no longer matches its card's SHA-256."""
    path = tmp_path / source.name
    path.with_suffix(".md").write_bytes(source.with_suffix(".md").read_bytes())
    if how == "byte":
        blob = bytearray(source.read_bytes())
        blob[len(blob) // 2] ^= 0x01
        path.write_bytes(bytes(blob))
    else:
        # A well-formed NPZ with one reward changed, which only the hash can tell apart.
        with np.load(source, allow_pickle=False) as npz:
            arrays = {name: npz[name] for name in npz.files}
        arrays["rewards"] = arrays["rewards"].copy()
        arrays["rewards"][0] += 1.0
        with path.open("wb") as f:
            np.savez(f, **arrays)
    return path


@pytest.mark.parametrize("how", ["byte", "array"])
def test_load_refuses_a_file_that_does_not_match_its_card(drift_dataset, tmp_path, how):
    _, source = drift_dataset
    path = _tampered(source, tmp_path, how)
    with pytest.raises(ValueError, match="SHA-256"):
        ExpertDataset.load(path)
