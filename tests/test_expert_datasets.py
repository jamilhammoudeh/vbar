"""The oracle expert agent and its expert datasets.

`OracleAgent` is an ordinary agent: it gets the scenario's public view, its own random stream,
the observations and the agent-safe info, solves the CW fuel oracle from its first observation
(perfect navigation makes that the start) and flies the plan. `expert_dataset` runs it on public
seeds and keeps only what an agent saw and did; `ExpertDataset.save(path)` writes the arrays as an
NPZ file and the dataset card beside it as `path.with_suffix(".md")`, and `ExpertDataset.load`
reads both back.

Oracle episodes are shortened from 360 steps of 10 s to 34 steps of 30 s through `make`'s `dt`
and `max_steps`, and check the soft speed constraints at 2 samples per step instead of 20.
Those checks take most of the simulation time and cost the same per step whatever its length;
the goal and the CW dynamics are unchanged, and the oracle plans for the steps it is given.
Tests that only solve use a 100-step horizon of 10 s steps, the way the free-time oracle tests
shorten it. Format and leak tests use the drift agent on episodes of a few steps. The full
datasets are generated by a benchmark script.
"""

